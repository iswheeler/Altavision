function timeout(ms, signal) {
  return new Promise((res, rej) => {
    if (signal?.aborted) return rej(signal.reason);
    let id = setTimeout(res, ms);
    signal?.addEventListener("abort", () => {
      clearTimeout(id);
      rej(signal.reason);
    });
  });
}

