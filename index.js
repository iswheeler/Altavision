class Window {
    dragStartX = 0;
    dragStartY = 0;
    isDragging = false;
    id = 0; // Unique ID should be set by the parent

    preDragX = 0;
    preDragY = 0;
    closeWithAnimation = true;
    windowManager = null;

    domElement = null;
    onFocus = function() {};

    attachDomElement(domElement_in, x, y) {

        this.domElement = domElement_in;

        this.preDragX = x;
        this.preDragY = y;
        this.domElement.style.top = this.preDragY + "px";
        this.domElement.style.left = this.preDragX + "px";

        this.domElement.querySelector(".titlebar").addEventListener("mousedown", this.onTitleBarMouseDown.bind(this));

        document.addEventListener("mouseup", this.onGlobalMouseUp.bind(this));
        document.addEventListener("mousemove", this.onMouseMove.bind(this));

        this.domElement.querySelector(".titlebar").addEventListener("mouseup", this.onTitleBarMouseUp.bind(this));
        this.domElement.querySelector(".window_frame_button.close").addEventListener("click", ((e) => {
            this.closeWindow();
        }).bind(this));
    }

    create(x, y, width, height, title, className, content, theme) {
        var closeButtonURI = (theme == "plastic") ? CLOSE_BUTTON_URI_PLASTIC : CLOSE_BUTTON_URI_98;
        var minimizeButtonURI = (theme == "plastic") ? MINIMIZE_BUTTON_URI_PLASTIC : MINIMIZE_BUTTON_URI_98;
        var maximizeButtonURI = (theme == "plastic") ? MAXIMIZE_BUTTON_URI_PLASTIC : MAXIMIZE_BUTTON_URI_98;

        this.dragStartX = x;
        this.dragStartY = y;

        var frame = document.createElement("div");
      frame.className = "window_frame";

      frame.style.width = width;
      frame.style.height = height;

      //   frame.style.width = width+"px";
      // frame.style.height = height + "px";

      // Additional buttons
      // <span class="window_frame_button"><img draggable="false" src="${maximizeButtonURI}"></span>
      // <span class="window_frame_button"><img draggable="false" src="${minimizeButtonURI}"></span>

        if (className) frame.classList.add(className);
        frame.innerHTML = `
            <div class="titlebar">
                <span class="title">${title}</span>

                <span class="window_frame_button close"><img draggable="false" src="${closeButtonURI}"></span>
            </div>
            <div class="content">
                ${content}
            </div>`;

      frame.querySelector(".content").addEventListener("click", () => {
        this.windowManager.bringToTop(this.id);
      });
      document.querySelector(".wrapper").appendChild(frame);

        this.attachDomElement(frame, x, y);
    }

    onGlobalMouseUp() {
        this.isDragging = false;
    }

    onTitleBarMouseDown(e) {
        // console.log("Started dragging at ", e.clientX, e.clientY);
        // console.log("dragStartX: ", this.dragStartX, "dragStartY: ", this.dragStartY);
        // console.log("preDragX: ", this.preDragX, "preDragY: ", this.preDragY);
        this.isDragging = true;
        // this.dragStartX = e.clientX;
        // this.dragStartY = e.clientY;
        this.dragStartX = this.windowManager.mousePosition.x;
        this.dragStartY = this.windowManager.mousePosition.y;

        this.windowManager.bringToTop(this.id);
    }


    onTitleBarMouseUp(e) {
        // console.log("Got mouse up!");
        this.preDragX = (e.clientX - this.dragStartX) + this.preDragX;
        this.preDragY = (e.clientY - this.dragStartY) + this.preDragY;
    }

    onMouseMove(e) {
        if (!this.isDragging) {
            // console.log("Not dragging! Stopping the function");
            return;
        }

        var newX = (e.clientX - this.dragStartX) + this.preDragX;
        var newY = (e.clientY - this.dragStartY) + this.preDragY;

        // console.log("Mouse Moved to ", newX, newY);

        this.domElement.style.left = newX + "px";
        this.domElement.style.top = newY + "px";
    }

    setZIndex(new_z_index) {
        this.domElement.style.zIndex = new_z_index;
    }

    closeWindow() {
        this.domElement.querySelector(".titlebar").removeEventListener("mousedown", this.onTitleBarMouseDown.bind(this));

        document.removeEventListener("mouseup", this.onGlobalMouseUp.bind(this));
        document.removeEventListener("mousemove", this.onMouseMove.bind(this));

        this.domElement.removeEventListener("mouseup", this.onTitleBarMouseUp.bind(this));
        console.log("this.closeWithAnimation is ",this.closeWithAnimation);
        if (this.closeWithAnimation) {
            this.domElement.classList.add("closing_animation");
            setTimeout(() => {this.domElement.remove();}, 300);
        } else {
            this.domElement.remove();
        }
        this.windowManager.removeRecord(this.id);
        // ();
    }

}

class WindowManager {
    // TODO: Implement onFocus attribute and make the last-clicked-on window appear on top!

    isStartMenuShowing = false;
    currentTheme = "plastic";
    windows = {};
    mousePosition = {x: 0, y: 0}; // For windows to reach in and read
    highestZIndex = 10000; // Z indexes should be between 10000 and 10999


    constructor() {
        document.addEventListener("mousemove", (function(e) {
            this.mousePosition.x = e.clientX;
            this.mousePosition.y = e.clientY;
        }).bind(this));
    }

    closeStartMenu() {
        // TODO: Make StartMenu its own class
        this.isStartMenuShowing = false;
    }

    setStartMenuVisibility = (visible) => {
        if (visible) {
            document.querySelector(".startmenu").classList.remove("hidden");
        } else {
            document.querySelector(".startmenu").classList.add("hidden");
        }
    }

    toggleStartMenu = () => {
        if (this.isStartMenuShowing) {
            this.setStartMenuVisibility(false);
        } else {
            this.setStartMenuVisibility(true);
        }
        this.isStartMenuShowing = !this.isStartMenuShowing;

    }

    removeRecord = (id) => {
        // When a window is closed, it calls this to remove the record
        delete this.windows[id];
    }

    bringToTop = (id) => {
        // Brings a window to the top
        this.highestZIndex++;
        this.windows[id].setZIndex(this.highestZIndex);
        // TODO: Reset the Z indexes if they get too big?
    }

    createWindow = (x, y, width, height, title, className, content) => {
        // TODO: Add this to the local JSON object to keep track of it in e.g. the taskbar
        var win = new Window();
        var id = Math.random().toString(36).slice(2); // Random string ID

        let css_width = width + "px";
      let css_height = height + "px";

        if (window.mobileCheck()) {
          x = 0;
          y = 0;
          css_width = "100%";
          css_height = "calc(100% - 1.8rem)";
          wManager.closeAll(); // Only allow one window at a time on mobile
        }


        win.create(x, y, css_width, css_height, title, className, content, this.currentTheme);
        win.id = id;
        win.closeWithAnimation = (this.currentTheme == "plastic");
        this.highestZIndex++;
        win.setZIndex(this.highestZIndex);
        console.log("win.closeWithAnimation set to ", win.closeWithAnimation);
        win.windowManager = this;

        this.windows[id] = win;
    }

  closeAll = () => {
    Array.from(document.querySelectorAll(".window_frame")).forEach(frame => {
      frame.remove();
    })
  }
}




